text = "  hello python  "
print("Upper:", text.upper())
print("Lower:", text.lower())
print("Capitalize:", text.capitalize())
print("Title:", text.title())
print("Count:", text.count("o"))
print("Find:", text.find("o"))
print("Rfind:", text.rfind("o"))
print("Index:", text.index("p"))
print("Replace:", text.replace("python", "world"))
print("Split:", text.split())
print("Join:", "-".join(["hello", "python"]))
print("Strip:", text.strip())
print("Lstrip:", text.lstrip())
print("Rstrip:", text.rstrip())
print("Startswith:", text.strip().startswith("hello"))
print("Endswith:", text.strip().endswith("python"))